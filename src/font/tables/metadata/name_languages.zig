comptime {
    for (entries[1..], entries[0 .. entries.len - 1]) |current, previous| {
        if (current.id <= previous.id) {
            @compileError("legacy name-language mappings must be unique and sorted");
        }
    }
}

pub fn find(id: u16) ?[]const u8 {
    var low: usize = 0;
    var high: usize = entries.len;
    while (low < high) {
        const mid = low + (high - low) / 2;
        if (entries[mid].id < id) {
            low = mid + 1;
        } else {
            high = mid;
        }
    }
    if (low == entries.len or entries[low].id != id) return null;
    return entries[low].tag;
}
